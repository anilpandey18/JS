// In JavaScript, `x++` is called the postfix increment operator. 
// It first uses the current value of `x` and then increases `x` by 1.For example, 
// if `x = 5`, then `y = x++` gives `y = 5` and `x = 6`. On the other hand, `++x` is called the prefix increment operator. 
// It first increases `x` by 1 and then uses the new value. For example, if `x = 5`, then `y = ++x` gives `x = 6` 
// and `y = 6`. Simply remember: **postfix means use first, then increase; prefix means increase first, then use.

